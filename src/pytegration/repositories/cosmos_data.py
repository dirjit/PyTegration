"""The curated Cosmic Explorer data set: objects, zoom levels, history, quiz, careers.

LESSON: Module 11 (Cosmic Explorer). See docs/11-cosmic-explorer.md
LAYER:  repositories (data source)

WHY keep the data as Python constants?
    It is small, read-only, reviewed by humans, and versioned with the code — so
    a fact correction is an ordinary, reviewable diff. Python literals are also
    type-checked by mypy (a typo'd field name fails the build), which a JSON file
    would not give us. If the atlas ever grew large or editable, the
    `CosmosCatalog` interface would stay the same and only this module would be
    swapped for a database-backed source.

ACCURACY NOTE (for contributors):
    Numbers are rounded, kid-friendly values from NASA/ESA fact sheets. Several
    are genuinely uncertain (Betelgeuse's size and distance, the number of moons,
    the Milky Way's width) and the text says "about" or "at least" on purpose:
    showing that science keeps updating is part of the lesson.
"""

